<?php
// Устанавливаем заголовок, чтобы указать, что ответ в формате JSON
header('Content-Type: application/json');

// Получаем сырой JSON-данные из тела запроса
$data = json_decode(file_get_contents('php://input'), true);

// Проверяем, были ли данные получены
if ($data) {
    // Вы можете здесь обработать данные, например, сохранить в базу данных
    // Или выполнить другие операции в зависимости от вашего приложения

    // Пример простого ответа
    $response = [
        'status' => 'success',
        'message' => 'Данные успешно получены',
        'data' => $data // можете отправить полученные данные обратно, если нужно
    ];

    // Отправляем ответ в формате JSON
    echo json_encode($response);
} else {
    // Если данные не получены, отправляем ошибку
    $response = [
        'status' => 'error',
        'message' => 'Ошибка при получении данных'
    ];

    echo json_encode($response);
}
